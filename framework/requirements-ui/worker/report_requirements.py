def p(name, unit=None, kind='float', expression=None):
    return P(name, kind=kind, unit=unit, expression=expression)


def requirement(name, identifier, report, text, parameters, predicate, affected, study,
                parent=(), evidence=()):
    source = 'final_report/eps-requirements.tex' if report.startswith('EPS-') else 'final_report/requirements.tex'
    return R(
        name=name, id=identifier, context='eps', text=text,
        origin=f'{source}#{report} | Study: {study} | Supply applicable bounds and independently assigned limits.',
        affected=affected, parameters=tuple(parameters) + (
            P('applicable_conditions_assessed', kind='boolean', exposed=False),
        ) + tuple(P(flag, kind='boolean', exposed=False) for flag in evidence),
        # As with the existing report requirements, evidence methods are chosen
        # by the engineer. An empty study establishes no automatic conformity.
        condition='', acceptance=f'({predicate}) and applicable_conditions_assessed'
        + ''.join(f' and {flag}' for flag in evidence),
        derives_from=parent, auto_populate=True,
    )


